import type { Api, Model } from "@oh-my-pi/pi-ai";
import type { ProviderConfig } from "@oh-my-pi/pi-coding-agent";
import {
  buildCodexAlias,
  CODEX_PROVIDER_ID,
  type CodexDeps,
} from "./codex.js";
import {
  type AliasDefinition,
  type AliasLoadResult,
  type LoadConfigOptions,
} from "./config.js";

export interface AliasHost {
  registerProvider(name: string, config: ProviderConfig): void;
  unregisterProvider(name: string): void;
  on(
    event: "session_start" | "before_agent_start",
    handler: (event: unknown, ctx: unknown) => unknown,
  ): void;
}

export interface AliasRuntimeDeps {
  codex: CodexDeps;
  loadConfig(options?: LoadConfigOptions): AliasLoadResult;
}

type ModelRegistryLike = {
  getAll(): Model<Api>[];
};

type EventContextLike = {
  cwd?: string;
  hasUI?: boolean;
  modelRegistry?: ModelRegistryLike;
  ui?: {
    notify(message: string, level?: "info" | "warning" | "error"): void;
  };
};

export function registerAliases(
  pi: AliasHost,
  deps: AliasRuntimeDeps,
  initialCwd = process.cwd(),
): void {
  let registered = new Map<string, ProviderConfig>();
  let lastSignature = "";
  let lastErrorSignature = "";

  const refresh = (ctx?: EventContextLike) => {
    const cwd = ctx?.cwd ?? initialCwd;
    const loaded = deps.loadConfig({ cwd });
    const sourceModels = resolveSourceModels(ctx?.modelRegistry, deps.codex);
    const signature = registrationSignature(loaded.aliases, sourceModels);

    if (signature !== lastSignature) {
      let registrationSucceeded = true;
      const planned: ProviderRegistration[] = [];

      for (const alias of loaded.aliases) {
        try {
          planned.push(...adaptersFor(alias, deps.codex, sourceModels));
        } catch (error) {
          registrationSucceeded = false;
          loaded.errors.push(
            `${alias.providerId}: ${error instanceof Error ? error.message : String(error)}`,
          );
        }
      }

      const duplicateIds = duplicateProviderIds(planned);
      if (duplicateIds.length > 0) {
        registrationSucceeded = false;
        for (const providerId of duplicateIds) {
          loaded.errors.push(
            `${providerId}: duplicate provider id generated by alias configuration`,
          );
        }
      }

      const occupiedIds = preexistingProviderIds(
        planned,
        registered,
        deps.codex,
      );
      if (occupiedIds.length > 0) {
        registrationSucceeded = false;
        for (const providerId of occupiedIds) {
          loaded.errors.push(
            providerId + ": provider id is already registered by OMP",
          );
        }
      }

      const next = new Map<string, ProviderConfig>();
      const attempted: string[] = [];
      if (registrationSucceeded) {
        for (const { providerId, config } of planned) {
          try {
            attempted.push(providerId);
            pi.registerProvider(providerId, config);
            next.set(providerId, config);
          } catch (error) {
            registrationSucceeded = false;
            loaded.errors.push(
              `${providerId}: ${error instanceof Error ? error.message : String(error)}`,
            );
            break;
          }
        }
      }

      if (!registrationSucceeded) {
        for (const providerId of [...attempted].reverse()) {
          try {
            const previous = registered.get(providerId);
            if (previous) pi.registerProvider(providerId, previous);
            else pi.unregisterProvider(providerId);
          } catch (error) {
            loaded.errors.push(
              providerId +
                ": rollback failed: " +
                (error instanceof Error ? error.message : String(error)),
            );
          }
        }
      }

      if (registrationSucceeded) {
        for (const providerId of registered.keys()) {
          if (!next.has(providerId)) {
            pi.unregisterProvider(providerId);
          }
        }

        registered = next;
        lastSignature = signature;
      }
    }

    reportErrors(loaded.errors, ctx);
  };

  const reportErrors = (errors: readonly string[], ctx?: EventContextLike) => {
    const signature = errors.join("\n");
    if (!signature) {
      lastErrorSignature = "";
      return;
    }
    if (signature === lastErrorSignature) return;
    lastErrorSignature = signature;
    const message =
      errors.length === 1
        ? `omp-sub-alias: ${errors[0]}`
        : `omp-sub-alias: ${errors[0]} (+${errors.length - 1} more)`;

    if (ctx?.hasUI && ctx.ui) ctx.ui.notify(message, "error");
    else console.warn(message);
  };

  refresh();

  pi.on("session_start", (_event: unknown, ctx: unknown) =>
    refresh(asContext(ctx)),
  );
  pi.on("before_agent_start", (_event: unknown, ctx: unknown) =>
    refresh(asContext(ctx)),
  );
}

type ProviderRegistration = {
  providerId: string;
  config: ProviderConfig;
};

function preexistingProviderIds(
  registrations: readonly ProviderRegistration[],
  registered: ReadonlyMap<string, ProviderConfig>,
  codex: CodexDeps,
): string[] {
  const occupied = new Set<string>();
  for (const { providerId } of registrations) {
    if (registered.has(providerId)) continue;
    if (codex.getProviderDefinition(providerId)) occupied.add(providerId);
  }
  return [...occupied].sort();
}

function duplicateProviderIds(
  registrations: readonly ProviderRegistration[],
): string[] {
  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const { providerId } of registrations) {
    if (seen.has(providerId)) duplicates.add(providerId);
    else seen.add(providerId);
  }
  return [...duplicates].sort();
}

function adaptersFor(
  alias: AliasDefinition,
  codex: CodexDeps,
  sourceModels: readonly Model<Api>[],
): ProviderRegistration[] {
  if (alias.provider === CODEX_PROVIDER_ID) {
    const built = buildCodexAlias(alias, codex, sourceModels);
    return [
      { providerId: alias.providerId, config: built.config },
      ...(built.device ? [built.device] : []),
    ];
  }
  throw new Error(`unsupported provider: ${alias.provider}`);
}

function resolveSourceModels(
  registry: ModelRegistryLike | undefined,
  codex: CodexDeps,
): Model<Api>[] {
  const live =
    registry
      ?.getAll()
      .filter(
        (model) =>
          model.provider === CODEX_PROVIDER_ID &&
          model.api === "openai-codex-responses",
      ) ?? [];

  if (live.length > 0) return live;

  return codex
    .getBundledModels(CODEX_PROVIDER_ID)
    .filter(
      (model) =>
        model.provider === CODEX_PROVIDER_ID &&
        model.api === "openai-codex-responses",
    )
    .map((model) => structuredClone(model));
}

function registrationSignature(
  aliases: readonly AliasDefinition[],
  sourceModels: readonly Model<Api>[],
): string {
  return JSON.stringify({
    aliases,
    models: sourceModels,
  });
}

function asContext(value: unknown): EventContextLike | undefined {
  if (!value || typeof value !== "object") return undefined;
  return value as EventContextLike;
}
